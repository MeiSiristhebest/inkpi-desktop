/**
 * generate-model-catalog.mjs — 从 inkpi 运行时的已构建目录（@inkpi/ai dist/catalog.js）
 * 生成桌面端内置模型目录快照 src/core/modelCatalog.generated.ts。
 *
 * 用途（对齐参考实现的 "目录: 内置快照 · N 个模型" 能力）：
 *  1. 设置中心「模型目录」页脚显示内置快照规模与生成时间；
 *  2. 模型勾选面板用快照为手动填写/拉取的模型 ID 预填 上下文窗口/最大输出/思考支持。
 *
 * 运行前提：相邻仓库 inkpi 已完成构建（inkpi/packages/ai/dist/catalog.js 存在）。
 * CI 中无相邻仓库时本脚本直接退出（快照已随仓库提交，无需重新生成）。
 *
 * 用法：node scripts/generate-model-catalog.mjs
 */
import { existsSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const desktopRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const catalogSource = path.resolve(desktopRoot, '../inkpi/packages/ai/dist/catalog.js')
const outPath = path.resolve(desktopRoot, 'src/core/modelCatalog.generated.ts')

if (!existsSync(catalogSource)) {
  console.log('[generate-model-catalog] 未找到相邻仓库构建产物：')
  console.log(`  ${catalogSource}`)
  console.log('请先在 inkpi 仓库执行构建（pnpm build）；CI 环境直接使用已提交的快照，无需重新生成。')
  process.exit(0)
}

const { KNOWN_MODELS } = await import(pathToFileURL(catalogSource).href)

const snapshot = KNOWN_MODELS.map((m) => ({
  id: m.id,
  name: m.name,
  provider: String(m.provider),
  contextWindow: m.contextWindow,
  maxTokens: m.maxTokens,
  supportsThinking: !!m.supportsThinking,
  supportsVision: !!m.supportsVision,
}))

const generatedAt = new Date().toISOString().slice(0, 10)

const body = `/**
 * AUTOGENERATED FILE - DO NOT EDIT MANUALLY
 * Generated by scripts/generate-model-catalog.mjs from @inkpi/ai KNOWN_MODELS
 * （inkpi/packages/ai/dist/catalog.js，已过滤 faux/mock 测试条目）。
 * 重新生成：node scripts/generate-model-catalog.mjs（需相邻 inkpi 仓库已构建）。
 */

export interface ModelCatalogSnapshot {
  id: string
  name: string
  provider: string
  contextWindow: number
  maxTokens: number
  supportsThinking: boolean
  supportsVision?: boolean
}

export const MODEL_CATALOG_GENERATED_AT = ${JSON.stringify(generatedAt)}

export const MODEL_CATALOG: ModelCatalogSnapshot[] = [
${snapshot
  .map((m) => `  ${JSON.stringify(m)}`)
  .join(',\n')}
]

const byId = new Map(MODEL_CATALOG.map((m) => [m.id, m]))

/**
 * 按模型 ID 精确查快照。未命中时再尝试去 provider 前缀/带前缀两种形式，
 * 与运行时 catalog 同时收录 "provider/model" 与 "model" 两种 ID 的约定一致。
 */
export function lookupCatalogModel(id: string): ModelCatalogSnapshot | undefined {
  if (byId.has(id)) return byId.get(id)
  const bare = id.includes('/') ? id.slice(id.lastIndexOf('/') + 1) : id
  return byId.get(bare) ?? byId.get(id)
}
`

writeFileSync(outPath, body, 'utf8')

// 生成后自动用仓库内 Prettier 格式化，保证重复生成不产生格式噪音
try {
  const { execFileSync } = await import('node:child_process')
  execFileSync(process.platform === 'win32' ? 'npx.cmd' : 'npx', ['prettier', '--write', outPath], {
    stdio: 'inherit',
    cwd: desktopRoot,
  })
} catch {
  console.log('[generate-model-catalog] Prettier 不可用，跳过格式化（不影响功能）')
}
console.log(`[generate-model-catalog] 已写入 ${path.relative(desktopRoot, outPath)}：${snapshot.length} 个模型（${generatedAt}）`)
